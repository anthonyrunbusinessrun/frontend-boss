import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { voucherNumber as computedVoucherNo } from "./compute";
import { choicesFromNames, isUserEditable } from "./fields";
import { activeFilterCount, applyFilters, defaultRule, describeRule, isIncomplete, opsFor } from "./query";
import { formatCode, isValidPrefix, nextFromMax, nextNumber, parseCode } from "./sequence";
import type { FieldDef, FilterRule, RecordRow } from "./types";
import { validateRecordInput } from "./validate";
import { MANIFEST_COLUMNS, PACK_COLUMNS, VOUCHER_DOCUMENT, formatVoucherDate, joinRows, parseRows, voucherNumber } from "./voucher";

const f = (key: string, type: FieldDef["type"], extra: Partial<FieldDef> = {}): FieldDef => ({ key, name: key, type, options: {}, position: 0, required: false, primary: false, ...extra });
const rule = (field: string, op: FilterRule["op"], extra: Partial<FilterRule> = {}): FilterRule => ({ id: field + op, join: "and", field, op, ...extra });

describe("sequential codes", () => {
  const seq = { prefix: "A-" };
  it("formats and parses codes with prefix and padding", () => {
    assert.equal(formatCode(seq, 4702), "A-4702");
    assert.equal(formatCode({ prefix: "", pad: 5 }, 4105), "04105");
    assert.equal(formatCode({ prefix: "", pad: 5 }, 123456), "123456");
    assert.equal(parseCode(seq, "A-4642"), 4642);
    assert.equal(parseCode(seq, "A-"), null);
    assert.equal(parseCode(seq, "B-4642"), null);
    assert.equal(parseCode(seq, "A-12x"), null);
    assert.equal(parseCode({ prefix: "", pad: 5 }, "04101"), 4101);
  });

  it("next = highest in use + 1 (not the count), gaps are not refilled", () => {
    assert.equal(nextNumber(seq, ["A-1001", "A-1002", "A-1003"], null), 1004);
    assert.equal(nextNumber(seq, ["A-4642", "A-4643", "A-4701"], null), 4702, "16 records with gaps: the highest wins");
    assert.equal(nextNumber(seq, [], null), 1);
    assert.equal(nextNumber(seq, ["A-5", "legacy", "FL-9000"], null), 6, "codes of another format are ignored");
  });

  it("the counter keeps a deleted record's code from being reused", () => {
    assert.equal(nextNumber(seq, ["A-10"], 15), 15, "A-14 was issued and deleted: the counter is ahead");
    assert.equal(nextNumber(seq, ["A-20"], 15), 21);
    assert.equal(nextFromMax(null, null), 1);
    assert.equal(nextFromMax(9, 3), 10);
  });

  it("only safe prefixes are accepted", () => {
    assert.ok(isValidPrefix("A-") && isValidPrefix("") && isValidPrefix("LLG_1"));
    assert.ok(!isValidPrefix("A'; DROP") && !isValidPrefix("^.*$"));
  });

  it("a code is generated by the server: never taken from a create, never changeable on update", () => {
    const code = f("code", "text", { required: true, options: { sequence: seq } });
    const title = f("title", "text");
    const created = validateRecordInput([code, title], { code: "HACK", title: "x" }, { mode: "create" });
    assert.deepEqual(created.errors, {}, "not required from the client");
    assert.equal("code" in created.values, false);
    const updated = validateRecordInput([code, title], { code: "HACK" }, { mode: "update" });
    assert.match(updated.errors.code, /assigned automatically/);
    assert.equal(isUserEditable(code, "create"), false);
    assert.equal(isUserEditable(code, "update"), false);
    assert.equal(isUserEditable(title, "create"), true);
  });
});

describe("voucher document helpers", () => {
  it("numbers vouchers like the sample: type + (I + 4000)", () => {
    assert.equal(voucherNumber({ id: "x", i: 11574, docType: "FD" }), "LLG-FD-15574");
    assert.equal(voucherNumber({ id: "x", i: 11575, docType: "FT" }), "LLG-FT-15575");
    assert.equal(voucherNumber({ id: "x", i: 11575, docType: "BL" }), "LLG-BL-15575");
    assert.equal(voucherNumber({ id: "x", i: 11595, docType: "IN" }), "LLG-IN-15595");
    assert.equal(voucherNumber({ id: "x", i: 11575 }), "LLG-BL-15575", "legacy vouchers are Bills of Lading");
    assert.equal(voucherNumber({ id: "x" }), "");
    assert.equal(computedVoucherNo({ number: "i", type: "docType", prefix: "LLG-", offset: 4000 }, { id: "x", i: 11574, docType: "FD" }), "LLG-FD-15574");
  });

  it("always points at the one supplied voucher PDF", () => {
    assert.deepEqual(VOUCHER_DOCUMENT, { url: "/vouchers/Voucher.pdf", name: "Voucher.pdf" });
  });

  it("formats dates as printed on the voucher", () => {
    assert.equal(formatVoucherDate("2026-07-09"), "7/9/2026");
    assert.equal(formatVoucherDate("nope"), "");
  });

  it("parses pipe-separated manifest rows and pads or folds cells", () => {
    const rows = parseRows("I/T-015 | Title | Desc | 7/13/2026 | 108\n\n  \nX | Y", MANIFEST_COLUMNS.length);
    assert.deepEqual(rows[0], ["I/T-015", "Title", "Desc", "7/13/2026", "108"]);
    assert.deepEqual(rows[1], ["X", "Y", "", "", ""]);
    assert.deepEqual(parseRows("a | b | c | d", 3)[0], ["a", "b", "c | d"], "extra cells fold into the last column");
    assert.deepEqual(parseRows(undefined, 3), []);
    assert.equal(parseRows("1|2|3|4|5|6", PACK_COLUMNS.length)[0].length, 6);
    assert.equal(joinRows([["a", "b"], ["c", "d"]]), "a | b\nc | d");
  });
});

describe("filter operators", () => {
  const status = f("status", "singleSelect", { name: "Status", options: { choices: choicesFromNames(["Todo", "Doing", "Done"]) } });
  const qty = f("qty", "number", { name: "Qty" });
  const due = f("due", "date", { name: "Due" });
  const tags = f("tags", "multiSelect", { name: "Tags", options: { choices: choicesFromNames(["a", "b", "c"]) } });
  const owner = f("owner", "link", { name: "Owner", options: { linkTable: "profiles" } });
  const done = f("done", "checkbox", { name: "Done" });
  const fields = [status, qty, due, tags, owner, done];
  const rows: RecordRow[] = [
    { id: "1", status: "Todo", qty: 5, due: "2026-07-01", tags: ["a"], owner: "p1", done: false },
    { id: "2", status: "Doing", qty: 50, due: "2026-07-10", tags: ["a", "b"], owner: "p2", done: true },
    { id: "3", status: "Done", qty: 500, due: "2026-07-20", tags: [], owner: null, done: false },
    { id: "4", status: null, qty: null, due: null, tags: ["c"], owner: "p1", done: true },
  ];
  const ids = (...r: FilterRule[]) => applyFilters(rows, r, fields).map((x) => x.id);

  it("offers only operators that make sense for each type", () => {
    const ops = (field: FieldDef) => opsFor(field).map((o) => o.op);
    assert.deepEqual(ops(done), ["is"]);
    assert.ok(ops(qty).includes("between") && ops(qty).includes("gt") && !ops(qty).includes("contains"));
    assert.ok(ops(due).includes("between") && ops(due).includes("before") && !ops(due).includes("gt"));
    assert.ok(ops(status).includes("isAnyOf") && !ops(status).includes("contains"));
    assert.ok(ops(tags).includes("isNoneOf") && ops(tags).includes("contains"));
    assert.ok(ops(owner).includes("isAnyOf") && !ops(owner).includes("contains"));
    assert.deepEqual(opsFor(f("t", "text")).map((o) => o.op), ["contains", "notContains", "is", "isNot", "isEmpty", "isNotEmpty"]);
  });

  it("number between is inclusive and open-ended when a bound is blank", () => {
    assert.deepEqual(ids(rule("qty", "between", { value: 5, value2: 50 })), ["1", "2"]);
    assert.deepEqual(ids(rule("qty", "between", { value: 50, value2: "" })), ["2", "3"]);
    assert.deepEqual(ids(rule("qty", "between", { value: "", value2: 50 })), ["1", "2"]);
  });

  it("date within a range, on, before and after", () => {
    assert.deepEqual(ids(rule("due", "between", { value: "2026-07-05", value2: "2026-07-15" })), ["2"]);
    assert.deepEqual(ids(rule("due", "between", { value: "2026-07-10", value2: "2026-07-20" })), ["2", "3"]);
    assert.deepEqual(ids(rule("due", "is", { value: "2026-07-10" })), ["2"]);
    assert.deepEqual(ids(rule("due", "after", { value: "2026-07-01" })), ["2", "3"]);
  });

  it("any-of / none-of for single select, multi select and links (assignee, category)", () => {
    assert.deepEqual(ids(rule("status", "isAnyOf", { values: ["Todo", "Done"] })), ["1", "3"]);
    assert.deepEqual(ids(rule("status", "isNoneOf", { values: ["Todo", "Done"] })), ["2", "4"], "records with no value are not in the set");
    assert.deepEqual(ids(rule("tags", "isAnyOf", { values: ["b", "c"] })), ["2", "4"]);
    assert.deepEqual(ids(rule("tags", "isNoneOf", { values: ["a"] })), ["3", "4"]);
    assert.deepEqual(ids(rule("owner", "isAnyOf", { values: ["p1"] })), ["1", "4"]);
    assert.deepEqual(ids(rule("owner", "isNoneOf", { values: ["p1", "p2"] })), ["3"]);
    assert.deepEqual(ids(rule("owner", "is", { value: "p2" })), ["2"]);
  });

  it("checkbox checked / unchecked, and combined conditions with and / or", () => {
    assert.deepEqual(ids(rule("done", "is", { value: true })), ["2", "4"]);
    assert.deepEqual(ids(rule("done", "is", { value: false })), ["1", "3"]);
    assert.deepEqual(ids(rule("done", "is", { value: true }), rule("owner", "is", { value: "p1" })), ["4"]);
    assert.deepEqual(ids(rule("done", "is", { value: true }), rule("status", "is", { value: "Todo", join: "or" })), ["1", "2", "4"]);
  });

  it("incomplete conditions are shown as such and hide nothing", () => {
    assert.ok(isIncomplete(rule("status", "isAnyOf", { values: [] })));
    assert.ok(isIncomplete(rule("qty", "between", { value: "", value2: "" })));
    assert.ok(isIncomplete(rule("qty", "gt", { value: "" })));
    assert.ok(!isIncomplete(rule("status", "isEmpty")));
    assert.equal(ids(rule("status", "isAnyOf", { values: [] })).length, 4);
    assert.equal(activeFilterCount([rule("status", "isAnyOf", { values: [] }), rule("qty", "gt", { value: 3 }), rule("gone", "is", { value: "x" })], fields), 1);
  });

  it("describes a condition in words for the active-filter pills", () => {
    assert.equal(describeRule(rule("status", "isAnyOf", { values: ["Todo", "Done"] }), status), "Status is any of Todo, Done");
    assert.equal(describeRule(rule("qty", "between", { value: 5, value2: 50 }), qty), "Qty is between 5 and 50");
    assert.equal(describeRule(rule("done", "is", { value: true }), done), "Done checked");
    assert.equal(describeRule(rule("status", "isEmpty"), status), "Status is empty");
    assert.equal(describeRule(rule("owner", "is", { value: "p1" }), owner, (v) => (v === "p1" ? "Ann" : v)), "Owner is Ann");
    assert.equal(defaultRule("r", qty).op, "eq");
  });
});
